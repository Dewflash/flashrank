import type { KeywordTag, TrackedApp, TrackedKeyword } from '@/types';

function daysAgo(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().split('T')[0];
}

function history(baseRank: number): TrackedKeyword['rankHistory'] {
  return Array.from({ length: 30 }, (_, index) => {
    const daysBack = 29 - index;
    const wave = Math.round(Math.sin(index / 3) * 2);
    return {
      date: daysAgo(daysBack),
      rank: Math.max(1, baseRank + wave),
    };
  });
}

